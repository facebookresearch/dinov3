"""
Evaluates the descriptions generated by one or more FossilVL settings with an LLM judge.

For every annotated label of a sample the judge answers whether the generated description states it (the same
claims as eval_labels_llm.py and as the recall term of the RL reward in train_fossilvl_grpo.py). Reported per
setting: label recall with a bootstrap 95% interval, mean P(yes), per-sample recall, the share of samples with
every label found, recall per category, and the recall of the reference descriptions on the same samples (the
ceiling set by the judge: references were written from the labels).

Inputs, one file per setting, in either format:
    selected.json style   {"refs": [...], "preds": [...], "labels": [...]}   ("labels" optional)
    generate.py output    {"generated": [{"reference": ..., "prediction": ..., ...}, ...]}
Samples without labels take them from --labels (eval/todos.json) by their reference text; references missing
from that file, or listed there with more than one label set, are skipped and counted.

Every (text, claim) pair is scored once and cached in <out_dir>/cache-<judge>.jsonl, so identical references
across settings are judged once and re-running with a new setting only scores its new descriptions.

    python geo/eval/eval_fossilvl.py --inputs sft=out/sft/generated.json rl=out/rl/generated.json \
        --judge Qwen/Qwen2.5-32B-Instruct --out_dir geo/eval/fossilvl_eval
"""
import hashlib
import json
import os
import sys
from argparse import ArgumentParser
from collections import Counter, defaultdict

import numpy as np

from eval_labels_llm import HFJudge, build_questions, score_pairs, summarize
from judge_reliability import normalize_labels


def labels_by_reference(path):
    """reference text -> set of its label sets (as sorted json) from a file with 'refs' and 'labels' lists."""
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    index = defaultdict(set)
    for ref, labels in zip(data['refs'], data['labels']):
        index[ref.strip()].add(json.dumps(normalize_labels(labels), ensure_ascii=False, sort_keys=True))
    return index


def load_setting(path, index, max_samples=None):
    """Samples of one setting with references, predictions and labels; counts of what was skipped and why."""
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if 'generated' in data:
        refs = [g['reference'] for g in data['generated']]
        preds = [g['prediction'] for g in data['generated']]
        given = [g.get('labels') for g in data['generated']]
    else:
        refs, preds = data['refs'], data['preds']
        given = data.get('labels') or [None] * len(refs)
    if not len(refs) == len(preds) == len(given):
        sys.exit(f'{path}: {len(refs)} references, {len(preds)} predictions, {len(given)} label sets')

    samples, skipped = [], Counter()
    for i, (ref, pred, labels) in enumerate(zip(refs, preds, given)):
        if max_samples is not None and i >= max_samples:
            break
        if labels is None:
            options = index.get(ref.strip(), set())
            if len(options) != 1:
                skipped['reference not in the labels file' if not options else 'reference with several label sets'] += 1
                continue
            labels = json.loads(next(iter(options)))
        labels = normalize_labels(labels)
        if not labels:
            skipped['no labels'] += 1
            continue
        samples.append({'index': i, 'reference': ref, 'prediction': pred, 'labels': labels})
    return samples, dict(skipped)


class Cache:
    """P(yes) per (text, claim), appended to a jsonl file as batches finish."""

    def __init__(self, path):
        self.path, self.scores = path, {}
        if os.path.exists(path):
            with open(path, 'r', encoding='utf-8') as f:
                for line in f:
                    try:
                        r = json.loads(line)
                    except json.JSONDecodeError:  # line cut by an interrupted run
                        continue
                    self.scores[r['key']] = r['p_yes']

    @staticmethod
    def key(text, claim):
        return hashlib.sha1(f'{text}\x00{claim}'.encode('utf-8')).hexdigest()

    def missing(self, pairs):
        seen, out = set(), []
        for text, claim in pairs:
            k = self.key(text, claim)
            if k not in self.scores and k not in seen:
                seen.add(k)
                out.append((text, claim))
        return out

    def add(self, pairs, probs):
        with open(self.path, 'a', encoding='utf-8') as f:
            for (text, claim), p in zip(pairs, probs):
                k = self.key(text, claim)
                self.scores[k] = p
                f.write(json.dumps({'key': k, 'p_yes': p}) + '\n')

    def get(self, text, claim):
        return self.scores[self.key(text, claim)]


def bootstrap_recall(questions, threshold, n_boot, seed=0):
    """95% interval of label recall, resampling samples (all labels of a sample stay together)."""
    by_sample = defaultdict(lambda: [0, 0])
    for q in questions:
        by_sample[q['sample']][0] += q['p_yes'] >= threshold
        by_sample[q['sample']][1] += 1
    found, total = np.array(list(by_sample.values()), dtype=float).T
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(found), size=(n_boot, len(found)))
    recalls = found[idx].sum(1) / total[idx].sum(1)
    return [float(np.percentile(recalls, 2.5)), float(np.percentile(recalls, 97.5))]


def evaluate(samples, cache, threshold, n_boot, judge_refs):
    labels = [s['labels'] for s in samples]
    result = {}
    for key, texts in (('preds', [s['prediction'] for s in samples]), ('refs', [s['reference'] for s in samples])):
        if key == 'refs' and not judge_refs:
            continue
        questions = build_questions(texts, labels)
        for q in questions:
            q['p_yes'] = cache.get(q['text'], q['claim'])
        summary = summarize(questions, len(samples), threshold)
        summary['mean_p_yes'] = float(np.mean([q['p_yes'] for q in questions])) if questions else 0.0
        summary['label_recall_ci95'] = bootstrap_recall(questions, threshold, n_boot) if questions else [0, 0]
        result[key] = {'summary': summary,
                       'questions': [{k: v for k, v in q.items() if k != 'text'} for q in questions]}
    return result


def render_report(summary):
    s = summary
    lines = ['# FossilVL evaluation', '',
             f"Judge `{s['judge']}`, threshold {s['threshold']}. A label counts as found when the judge's P(yes) that "
             'the description states it is at least the threshold. "Refs recall" is the same measure on the reference '
             'descriptions of the same samples: the ceiling set by the judge.', '',
             '| Setting | Samples | Labels | Label recall [95% CI] | Mean P(yes) | Per-sample recall '
             '| Samples with all labels | Refs recall |',
             '|---|---|---|---|---|---|---|---|']
    for name, r in s['settings'].items():
        p = r['preds']
        lo, hi = p['label_recall_ci95']
        refs = f"{r['refs']['label_recall']:.3f}" if 'refs' in r else '-'
        lines.append(f"| {name} | {p['n_samples']} | {p['n_labels']} | {p['label_recall']:.3f} [{lo:.3f}, {hi:.3f}] | "
                     f"{p['mean_p_yes']:.3f} | {p['mean_sample_recall']:.3f} | {p['samples_all_labels_found']:.3f} | "
                     f"{refs} |")
    cats = sorted({c for r in s['settings'].values() for c in r['preds']['per_category']},
                  key=lambda c: -max(r['preds']['per_category'].get(c, {}).get('total', 0)
                                     for r in s['settings'].values()))
    lines += ['', '## Recall per category', '', '| Setting | ' + ' | '.join(cats) + ' |', '|---|' + '---|' * len(cats)]
    for name, r in s['settings'].items():
        pc = r['preds']['per_category']
        lines.append(f'| {name} | ' + ' | '.join(
            f"{pc[c]['recall']:.3f} ({pc[c]['found']}/{pc[c]['total']})" if c in pc else '-' for c in cats) + ' |')
    skipped = {n: r['skipped'] for n, r in s['settings'].items() if r['skipped']}
    if skipped:
        lines += ['', '## Skipped samples', '']
        lines += [f'- {n}: ' + ', '.join(f'{v} {k}' for k, v in sk.items()) for n, sk in skipped.items()]
    return '\n'.join(lines) + '\n'


def main():
    parser = ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--inputs', nargs='+', required=True,
                        help='generated-caption files, one per setting, as path or name=path')
    parser.add_argument('--labels', default='geo/eval/todos.json',
                        help="labels by reference text, for inputs without labels ('refs' and 'labels' lists)")
    parser.add_argument('--out_dir', default='geo/eval/fossilvl_eval')
    parser.add_argument('--judge', default='Qwen/Qwen2.5-32B-Instruct')
    parser.add_argument('--load_in_4bit', action='store_true')
    parser.add_argument('--device_map', default=None, help="'auto' spreads a large judge over all visible GPUs")
    parser.add_argument('--batch_size', default=16, type=int, help='starting batch size, halved on out-of-memory')
    parser.add_argument('--threshold', default=0.5, type=float)
    parser.add_argument('--no_refs', dest='judge_refs', action='store_false',
                        help='do not judge the reference descriptions (the judge ceiling)')
    parser.add_argument('--bootstrap', default=1000, type=int, help='bootstrap resamples for the 95%% interval')
    parser.add_argument('--max', default=None, type=int, help='only the first N samples of every input')
    args = parser.parse_args()

    settings = {}
    for item in args.inputs:
        name, path = item.split('=', 1) if '=' in item else (os.path.splitext(os.path.basename(item))[0], item)
        if name in settings:
            sys.exit(f'two settings named {name!r}: use name=path')
        settings[name] = path

    index = labels_by_reference(args.labels)
    loaded = {}
    for name, path in settings.items():
        samples, skipped = load_setting(path, index, args.max)
        loaded[name] = (samples, skipped)
        print(f'{name}: {len(samples)} samples' + (f' (skipped: {skipped})' if skipped else ''))

    # every (text, claim) pair of every setting, scored once
    os.makedirs(args.out_dir, exist_ok=True)
    cache = Cache(os.path.join(args.out_dir, f"cache-{args.judge.replace('/', '__')}.jsonl"))
    pairs = []
    for samples, _ in loaded.values():
        labels = [s['labels'] for s in samples]
        texts = [s['prediction'] for s in samples] + ([s['reference'] for s in samples] if args.judge_refs else [])
        for q in build_questions(texts, labels * (2 if args.judge_refs else 1)):
            pairs.append((q['text'], q['claim']))
    unique = len({Cache.key(t, c) for t, c in pairs})
    todo = cache.missing(pairs)
    print(f'{len(pairs)} questions, {unique} distinct (identical references and descriptions are judged once), '
          f'{unique - len(todo)} already in the cache, {len(todo)} to judge')
    if todo:
        judge = HFJudge(args.judge, load_in_4bit=args.load_in_4bit, device_map=args.device_map)
        done, next_report = [0], [0]

        def progress(batch, probs):
            cache.add([todo[i] for i in batch], probs)
            done[0] += len(batch)
            if done[0] >= next_report[0] or done[0] == len(todo):  # about every 10%, readable in log files
                print(f'{done[0]}/{len(todo)} judged', flush=True)
                next_report[0] = done[0] + max(len(todo) // 10, 1)

        score_pairs(judge, todo, args.batch_size, on_batch=progress)

    summary = {'judge': args.judge, 'threshold': args.threshold, 'labels_file': args.labels, 'settings': {}}
    for name, (samples, skipped) in loaded.items():
        result = evaluate(samples, cache, args.threshold, args.bootstrap, args.judge_refs)
        with open(os.path.join(args.out_dir, f'{name}.json'), 'w', encoding='utf-8') as f:
            json.dump({'input': settings[name], 'judge': args.judge, 'threshold': args.threshold,
                       'skipped': skipped, **result}, f, ensure_ascii=False, indent=2)
        summary['settings'][name] = {'input': settings[name], 'skipped': skipped,
                                     **{k: v['summary'] for k, v in result.items()}}

    with open(os.path.join(args.out_dir, 'summary.json'), 'w', encoding='utf-8') as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)
    report = render_report(summary)
    with open(os.path.join(args.out_dir, 'report.md'), 'w', encoding='utf-8') as f:
        f.write(report)
    print(report)


if __name__ == '__main__':
    main()
